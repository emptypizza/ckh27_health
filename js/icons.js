/** 옆의 글자가 뜻을 전하므로 아이콘은 보조 기술에서 숨긴다. */
export function icon(name, size) {
  const svg = document.createElementNS(SVG_NAMESPACE, "svg");
  for (const [attribute, value] of Object.entries({ ...frame, width: String(size), height: String(size) })) {
    svg.setAttribute(attribute, value);
  }
  for (const [tag, attributes] of shapes[name]) {
    const shape = document.createElementNS(SVG_NAMESPACE, tag);
    for (const [attribute, value] of Object.entries(attributes)) shape.setAttribute(attribute, value);
    svg.append(shape);
  }
  return svg;
}
